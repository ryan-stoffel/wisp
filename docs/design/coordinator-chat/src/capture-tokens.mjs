// Regenerates tokens.css: the value of every --vscode-* variable the mocks use, read from a
// running Code - OSS build in Dark Modern, Light Modern, and both high contrast themes.
// Needs a built editor tree (see docs/editor-upgrade.md). Run it like render.mjs:
//   WISP_EDITOR_DIR=<repo>/editor/vscode node <repo>/docs/design/coordinator-chat/src/capture-tokens.mjs
import { mkdtempSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const { _electron } = createRequire(join(process.cwd(), 'index.js'))('playwright-core');
const src = dirname(fileURLToPath(import.meta.url));
const editorDir = process.env.WISP_EDITOR_DIR ?? join(src, '..', '..', '..', '..', 'editor', 'vscode');
const electronDir = join(editorDir, '.build', 'electron');
const appName = readdirSync(electronDir).find((name) => name.endsWith('.app'));
const executablePath = join(electronDir, appName, 'Contents', 'MacOS', appName.replace(/\.app$/, ''));

const used = new Set();
for (const file of readdirSync(src).filter((f) => /\.(css|js)$/.test(f) && f !== 'tokens.css')) {
	for (const match of readFileSync(join(src, file), 'utf8').matchAll(/--vscode-[A-Za-z0-9-]+/g)) {
		used.add(match[0]);
	}
}
const names = [...used].sort();

const themes = [
	['dark-modern', 'Default Dark Modern'],
	['light-modern', 'Default Light Modern'],
	['hc-dark', 'Default High Contrast'],
	['hc-light', 'Default High Contrast Light'],
];

let version = '';
const blocks = [];
for (const [key, themeName] of themes) {
	// macOS limits the IPC socket path in the user data dir to 103 characters, so keep it short.
	const profile = mkdtempSync(join(tmpdir(), 'wt-'));
	try {
		mkdirSync(join(profile, 'd', 'User'), { recursive: true });
		writeFileSync(join(profile, 'd', 'User', 'settings.json'), JSON.stringify({
			'workbench.colorTheme': themeName,
			'workbench.startupEditor': 'none',
			'telemetry.telemetryLevel': 'off',
			'update.mode': 'none',
		}));
		const app = await _electron.launch({
			executablePath,
			args: [editorDir, '--disable-extension=vscode.vscode-api-tests', `--user-data-dir=${join(profile, 'd')}`, `--extensions-dir=${join(profile, 'e')}`, '--skip-welcome', '--skip-release-notes'],
			env: { ...process.env, NODE_ENV: 'development', VSCODE_DEV: '1', VSCODE_CLI: '1' },
			timeout: 120_000,
		});
		try {
			const window = await app.firstWindow({ timeout: 120_000 });
			await window.locator('.monaco-workbench').waitFor({ timeout: 120_000 });
			await window.waitForTimeout(3000);
			version = await app.evaluate(({ app: electronApp }) => electronApp.getVersion());
			const values = await window.evaluate((list) => {
				const style = getComputedStyle(document.querySelector('.monaco-workbench'));
				return list.map((name) => [name, style.getPropertyValue(name).trim()]);
			}, names);
			const lines = values.map(([name, value]) => `\t${name}: ${value || 'initial'};`);
			blocks.push(`.theme-${key} {\n${lines.join('\n')}\n}`);
			console.log(`${key}: ${values.filter(([, value]) => value).length} of ${names.length} tokens set`);
		} finally {
			await app.close().catch(() => {});
		}
	} finally {
		rmSync(profile, { recursive: true, force: true });
	}
}

const header = `/* Generated by capture-tokens.mjs from a Code - OSS ${version} build. Do not edit by hand.\n * A token the theme leaves unset is written as initial, so the var() fallback applies, as it\n * does in the workbench, instead of inheriting from an enclosing theme on the same page. */\n\n`;
writeFileSync(join(src, 'tokens.css'), `${header}${blocks.join('\n\n')}\n`);
