// Regenerates tokens.css: the value of every --vscode-* variable the mocks use, read from the
// Agents window of a running Code - OSS development build in Dark Modern and Light Modern.
// The Agents window must open, so the tree needs the redirect in patch 0010 undone (#103).
// Run it like render.mjs, from a temp directory that has playwright-core:
//   WISP_EDITOR_DIR=<repo>/editor/vscode node <repo>/docs/design/agents-window/src/capture-tokens.mjs
// It uses a throwaway HOME, user data folder, and extensions folder, and in-memory secret storage,
// so it never reads the Keychain or your own agent sessions.
import { mkdtempSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const { _electron } = createRequire(join(process.cwd(), 'index.js'))('playwright-core');
const src = dirname(fileURLToPath(import.meta.url));
const editorDir = process.env.WISP_EDITOR_DIR ?? join(src, '..', '..', '..', '..', 'editor', 'vscode');
const electronDir = join(editorDir, '.build', 'electron');
const appName = readdirSync(electronDir).find((name) => name.endsWith('.app'));
const macos = join(electronDir, appName, 'Contents', 'MacOS');
const executablePath = join(macos, readdirSync(macos)[0]);

const used = new Set();
for (const file of readdirSync(src).filter((f) => /\.(css|js)$/.test(f) && f !== 'tokens.css')) {
	for (const match of readFileSync(join(src, file), 'utf8').matchAll(/--vscode-[A-Za-z0-9-]+/g)) {
		used.add(match[0]);
	}
}
const names = [...used].sort();

const themes = [
	['dark-modern', 'Default Dark Modern'],
	['light-modern', 'Default Light Modern'],
];

let css = '/* Generated by capture-tokens.mjs from the Agents window of a Code - OSS 1.139.0 build. Do not edit by hand.\n'
	+ ' * A token the theme leaves unset is written as initial, so the var() fallback applies. */\n';
for (const [id, label] of themes) {
	// macOS caps socket paths at 103 bytes, so the user data folder must have a short path.
	const tmp = mkdtempSync('/tmp/wisp-tokens-');
	const userData = join(tmp, 'u');
	mkdirSync(join(userData, 'User'), { recursive: true });
	writeFileSync(join(userData, 'User', 'settings.json'), JSON.stringify({ 'workbench.colorTheme': label }));
	const app = await _electron.launch({
		executablePath,
		args: [editorDir, '--agents', '--skip-sessions-welcome', '--user-data-dir', userData, '--extensions-dir', join(tmp, 'e'),
			'--use-inmemory-secretstorage', '--disable-extension=GitHub.copilot-chat', '--skip-release-notes'],
		env: { PATH: process.env.PATH, HOME: join(tmp, 'h'), NODE_ENV: 'development', VSCODE_DEV: '1', VSCODE_CLI: '1' },
	});
	try {
		let window;
		for (let i = 0; i < 60 && !window; i++) {
			window = app.windows().find((w) => w.url().includes('/sessions/'));
			if (!window) {
				await new Promise((r) => setTimeout(r, 500));
			}
		}
		if (!window) {
			throw new Error('the Agents window did not open; is patch 0010 still redirecting it?');
		}
		await window.waitForSelector('.monaco-workbench .part.sessionspart', { timeout: 60000 });
		// The theme applies after the parts render; wait until theme tokens resolve and settle.
		await window.waitForFunction(() => getComputedStyle(document.querySelector('.monaco-workbench')).getPropertyValue('--vscode-widget-border').trim() !== '', undefined, { timeout: 60000 });
		await new Promise((r) => setTimeout(r, 3000));
		const values = await window.evaluate((names) => {
			const style = getComputedStyle(document.querySelector('.monaco-workbench'));
			return names.map((n) => [n, style.getPropertyValue(n).trim()]);
		}, names);
		css += `\n.theme-${id} {\n${values.map(([n, v]) => `\t${n}: ${v || 'initial'};`).join('\n')}\n}\n`;
	} finally {
		await app.close();
		rmSync(tmp, { recursive: true, force: true });
	}
}
writeFileSync(join(src, 'tokens.css'), css);
console.log(`tokens.css: ${names.length} tokens, ${themes.length} themes`);
